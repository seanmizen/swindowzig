#!/usr/bin/env python3
"""Write libs/sw_text/src/shaping_tables.zig from the Unicode Character Database.

Usage:
    python3 -I libs/sw_text/tools/gen_shaping_tables.py <ucd-dir> > libs/sw_text/src/shaping_tables.zig

<ucd-dir> holds these files from https://www.unicode.org/Public/<version>/ucd/:
    ArabicShaping.txt (the joining types)
    UnicodeData.txt   (the general categories, and the presentation forms
                       from the <isolated>, <final>, <initial> and <medial>
                       decompositions in U+FB50 to U+FEFF)
"""

import os
import re
import sys

LAM = 0x0644
FORMS = ("isolated", "final", "initial", "medial")
TYPES = ("U", "R", "L", "D", "C", "T")


def data_lines(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            body = line.split("#", 1)[0].strip()
            if body:
                yield [field.strip() for field in body.split(";")]


def header_version(path):
    with open(path, encoding="utf-8") as f:
        first = f.readline()
    m = re.search(r"-(\d+\.\d+\.\d+)\.txt", first)
    return m.group(1) if m else "unknown"


def unicode_data(path):
    """Yield (code point, general category, decomposition) for each code point."""
    first = None
    for fields in data_lines(path):
        cp = int(fields[0], 16)
        name, category, decomposition = fields[1], fields[2], fields[5]
        if name.endswith(", First>"):
            first = cp
            continue
        lo = first if name.endswith(", Last>") else cp
        first = None
        for c in range(lo, cp + 1):
            yield c, category, decomposition


def joining_types(shaping_path, data_path):
    # ArabicShaping.txt: a code point that is not listed is T if its general
    # category is Mn, Me or Cf, and U if not.
    types = {}
    for cp, category, _ in unicode_data(data_path):
        if category in ("Mn", "Me", "Cf"):
            types[cp] = "T"
    for fields in data_lines(shaping_path):
        jt = fields[2]
        if jt not in TYPES:
            raise SystemExit(f"unknown joining type {jt}")
        types[int(fields[0], 16)] = jt

    ranges = []
    for cp in sorted(types):
        jt = types[cp]
        if jt == "U":
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == jt:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, jt])
    return types, ranges


def presentation_forms(data_path, types):
    """The forms of each letter, and the lam-alef ligatures."""
    forms = {}  # base -> {form: presentation code point}
    ligatures = {}  # alef -> {form: presentation code point}
    for cp, _, decomposition in unicode_data(data_path):
        if not 0xFB50 <= cp <= 0xFEFF:
            continue
        m = re.fullmatch(r"<(\w+)> ([0-9A-F ]+)", decomposition)
        if not m or m.group(1) not in FORMS:
            continue
        form = m.group(1)
        parts = [int(p, 16) for p in m.group(2).split()]
        if len(parts) == 1:
            base = parts[0]
            if types.get(base, "U") not in ("R", "L", "D"):
                continue
            by_form = forms.setdefault(base, {})
            if form in by_form:
                raise SystemExit(f"{base:04X} has two {form} forms")
            by_form[form] = cp
        elif len(parts) == 2 and parts[0] == LAM and types.get(parts[1]) == "R":
            # Lam followed by a right-joining letter (an alef): the
            # mandatory lam-alef ligature. The other ligatures in the block
            # are optional, and the shaper does not make them.
            if form not in ("isolated", "final"):
                raise SystemExit(f"lam-alef ligature {cp:04X} is {form}")
            ligatures.setdefault(parts[1], {})[form] = cp
    return forms, ligatures


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    ucd = sys.argv[1]
    shaping_path = os.path.join(ucd, "ArabicShaping.txt")
    data_path = os.path.join(ucd, "UnicodeData.txt")

    types, ranges = joining_types(shaping_path, data_path)
    forms, ligatures = presentation_forms(data_path, types)

    nominal = []  # (presentation code point, first base, second base or 0)
    for base, by_form in forms.items():
        for cp in by_form.values():
            nominal.append((cp, base, 0))
    for alef, by_form in ligatures.items():
        for cp in by_form.values():
            nominal.append((cp, LAM, alef))
    nominal.sort()
    if len({cp for cp, _, _ in nominal}) != len(nominal):
        raise SystemExit("a presentation form has two bases")

    out = sys.stdout
    out.write("//! GENERATED by libs/sw_text/tools/gen_shaping_tables.py. Do not edit.\n")
    out.write(f"//! Unicode Character Database {header_version(shaping_path)} (see THIRD_PARTY_NOTICES.md).\n")
    out.write("//! Code points that are not in `joining` are U (non-joining).\n")
    out.write("//! A presentation form of 0 means that Unicode has no such form.\n\n")
    out.write('const JoiningType = @import("shape.zig").JoiningType;\n\n')
    out.write("pub const JoiningRange = struct { lo: u21, hi: u21, type: JoiningType };\n")
    out.write("pub const Forms = struct { cp: u21, isolated: u21, final: u21, initial: u21, medial: u21 };\n")
    out.write("pub const Ligature = struct { alef: u21, isolated: u21, final: u21 };\n")
    out.write("pub const Nominal = struct { cp: u21, first: u21, second: u21 };\n\n")

    out.write("pub const joining = [_]JoiningRange{\n")
    for lo, hi, jt in ranges:
        out.write(f"    .{{ .lo = 0x{lo:04X}, .hi = 0x{hi:04X}, .type = .{jt} }},\n")
    out.write("};\n\n")

    out.write("/// The presentation forms of each letter that has one, by letter.\n")
    out.write("pub const forms = [_]Forms{\n")
    for base in sorted(forms):
        f = forms[base]
        values = ", ".join(f".{name} = 0x{f.get(name, 0):04X}" for name in FORMS)
        out.write(f"    .{{ .cp = 0x{base:04X}, {values} }},\n")
    out.write("};\n\n")

    out.write("/// The lam-alef ligatures: lam (U+0644) followed by `alef`.\n")
    out.write("pub const lam_alef = [_]Ligature{\n")
    for alef in sorted(ligatures):
        f = ligatures[alef]
        out.write(
            f"    .{{ .alef = 0x{alef:04X}, .isolated = 0x{f.get('isolated', 0):04X}, "
            f".final = 0x{f.get('final', 0):04X} }},\n"
        )
    out.write("};\n\n")

    out.write("/// The letters of each presentation form: `second` is 0 for one letter.\n")
    out.write("pub const nominal = [_]Nominal{\n")
    for cp, first, second in nominal:
        out.write(f"    .{{ .cp = 0x{cp:04X}, .first = 0x{first:04X}, .second = 0x{second:04X} }},\n")
    out.write("};\n")


if __name__ == "__main__":
    main()

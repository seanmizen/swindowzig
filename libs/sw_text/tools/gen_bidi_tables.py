#!/usr/bin/env python3
"""Write libs/sw_text/src/bidi_tables.zig from the Unicode Character Database.

Usage:
    python3 -I libs/sw_text/tools/gen_bidi_tables.py <ucd-dir> > libs/sw_text/src/bidi_tables.zig

<ucd-dir> holds these files from https://www.unicode.org/Public/<version>/ucd/:
    extracted/DerivedBidiClass.txt (or DerivedBidiClass.txt)
    BidiMirroring.txt
    BidiBrackets.txt
"""

import os
import re
import sys

CLASS_NAMES = {
    "Left_To_Right": "L",
    "Right_To_Left": "R",
    "Arabic_Letter": "AL",
    "European_Number": "EN",
    "European_Separator": "ES",
    "European_Terminator": "ET",
    "Arabic_Number": "AN",
    "Common_Separator": "CS",
    "Nonspacing_Mark": "NSM",
    "Boundary_Neutral": "BN",
    "Paragraph_Separator": "B",
    "Segment_Separator": "S",
    "White_Space": "WS",
    "Other_Neutral": "ON",
    "Left_To_Right_Embedding": "LRE",
    "Left_To_Right_Override": "LRO",
    "Right_To_Left_Embedding": "RLE",
    "Right_To_Left_Override": "RLO",
    "Pop_Directional_Format": "PDF",
    "Left_To_Right_Isolate": "LRI",
    "Right_To_Left_Isolate": "RLI",
    "First_Strong_Isolate": "FSI",
    "Pop_Directional_Isolate": "PDI",
}
SHORT = set(CLASS_NAMES.values())


def data_lines(path):
    with open(path, encoding="utf-8") as f:
        for line in f:
            body = line.split("#", 1)[0].strip()
            if body:
                yield [field.strip() for field in body.split(";")]


def header_version(path):
    with open(path, encoding="utf-8") as f:
        first = f.readline()
    m = re.search(r"-(\d+\.\d+\.\d+)\.txt", first)
    return m.group(1) if m else "unknown"


def parse_range(text):
    if ".." in text:
        lo, hi = text.split("..")
        return int(lo, 16), int(hi, 16)
    return int(text, 16), int(text, 16)


def class_table(path):
    classes = bytearray(0x110000)  # 0 is L.
    names = ["L"] + sorted(SHORT - {"L"})
    index = {name: i for i, name in enumerate(names)}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"#\s*@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)", line)
            if m:
                lo, hi = parse_range(m.group(1))
                value = CLASS_NAMES.get(m.group(2), m.group(2))
                classes[lo : hi + 1] = bytes([index[value]]) * (hi - lo + 1)
    for fields in data_lines(path):
        lo, hi = parse_range(fields[0])
        value = CLASS_NAMES.get(fields[1], fields[1])
        if value not in SHORT:
            raise SystemExit(f"unknown bidi class {fields[1]}")
        classes[lo : hi + 1] = bytes([index[value]]) * (hi - lo + 1)

    ranges = []
    start = 0
    for cp in range(1, 0x110001):
        if cp == 0x110000 or classes[cp] != classes[start]:
            name = names[classes[start]]
            if name != "L":
                ranges.append((start, cp - 1, name))
            start = cp
    return ranges


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    ucd = sys.argv[1]
    derived = os.path.join(ucd, "extracted", "DerivedBidiClass.txt")
    if not os.path.exists(derived):
        derived = os.path.join(ucd, "DerivedBidiClass.txt")
    mirroring = os.path.join(ucd, "BidiMirroring.txt")
    brackets_path = os.path.join(ucd, "BidiBrackets.txt")

    ranges = class_table(derived)
    mirrors = sorted((int(a, 16), int(b, 16)) for a, b in data_lines(mirroring))
    brackets = sorted((int(a, 16), int(b, 16), t) for a, b, t in data_lines(brackets_path))

    out = sys.stdout
    out.write("//! GENERATED by libs/sw_text/tools/gen_bidi_tables.py. Do not edit.\n")
    out.write(f"//! Unicode Character Database {header_version(derived)} (see THIRD_PARTY_NOTICES.md).\n")
    out.write("//! Code points that are not in `classes` are L.\n\n")
    out.write('const Class = @import("bidi.zig").Class;\n\n')
    out.write("pub const ClassRange = struct { lo: u21, hi: u21, class: Class };\n")
    out.write("pub const Mirror = struct { cp: u21, mirror: u21 };\n")
    out.write("pub const Bracket = struct { cp: u21, pair: u21, open: bool };\n\n")
    out.write("pub const classes = [_]ClassRange{\n")
    for lo, hi, name in ranges:
        out.write(f"    .{{ .lo = 0x{lo:04X}, .hi = 0x{hi:04X}, .class = .{name} }},\n")
    out.write("};\n\n")
    out.write("pub const mirrors = [_]Mirror{\n")
    for cp, mirror in mirrors:
        out.write(f"    .{{ .cp = 0x{cp:04X}, .mirror = 0x{mirror:04X} }},\n")
    out.write("};\n\n")
    out.write("pub const brackets = [_]Bracket{\n")
    for cp, pair, kind in brackets:
        is_open = "true" if kind == "o" else "false"
        out.write(f"    .{{ .cp = 0x{cp:04X}, .pair = 0x{pair:04X}, .open = {is_open} }},\n")
    out.write("};\n")


if __name__ == "__main__":
    main()
